def seed_reference(State, Country) -> None:
    """Add the states and countries that are missing. Takes the models so that
    migrations can pass their historical versions."""
    have = set(State.objects.values_list("code", flat=True))
    State.objects.bulk_create([State(code=c, name=n) for c, n in STATES if c not in have])
    have = set(Country.objects.values_list("code", flat=True))
    Country.objects.bulk_create([Country(code=c, name=n) for c, n in COUNTRIES if c not in have])
